"""Tests for the cron restart-loop defense (#30719).

Covers:
- cron create rejects prompts containing process lifecycle commands
- _contains_gateway_lifecycle_command pattern matching
"""

from argparse import Namespace

import pytest

from lliam_cli.cron import (
    _contains_gateway_lifecycle_command,
    cron_command,
)


# ---------------------------------------------------------------------------
# Defense 2: _contains_gateway_lifecycle_command pattern tests
